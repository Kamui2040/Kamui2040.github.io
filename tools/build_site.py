def note_page(post: dict) -> str:
    slug=post["slug"]
    title=post["translations"]["en"]["title"]
    excerpt=post["translations"]["en"]["excerpt"]
    body=f"""<main id="main" class="shell note-page">
  <nav aria-label="Back to About" class="note-back"><a class="text-link" href="/about/">{copy("about.back","Back to About")}</a></nav>
  <article class="note-article">
    <header class="note-article__header">
      <p class="eyebrow">{copy("about.notes","Notes")}</p>
      <p class="note-article__date"><time datetime="{post['date']}">{post['date']}</time></p>
      <h1 data-note-title>{localized(post,"title")}</h1>
      <p class="note-article__summary" data-note-summary>{localized(post,"excerpt")}</p>
    </header>
    <div class="note-article__body">{note_paragraphs(post)}</div>
    <div class="note-article__related">
      <p>{copy("about.newsHint","Project releases and downloads are listed separately in News.")}</p>
      <a class="text-link" href="/news/">{copy("about.newsAction","Go to News")}</a>
    </div>
  </article>
</main>"""
    return (head("about",title+" — K2040 Projects",excerpt,
                 f"/about/notes/{slug}/")+header("about")+body+footer())


def main() -> None:
    pages={"index.html":homepage(),"links/index.html":directory(),
           "news/index.html":news(),"about/index.html":about_page()}
    for post in NOTE_DATA:
        pages[f"about/notes/{post['slug']}/index.html"]=note_page(post)
    for name, html in pages.items():
        path=ROOT/name
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(html.rstrip("\n")+"\n",encoding="utf-8")
    (ROOT/"relaunch-site-news.js").write_text(editorial_news(),encoding="utf-8")
    print(f"Generated {len(pages)} accessible static pages and editorial news feed")

if __name__=="__main__":
    main()
