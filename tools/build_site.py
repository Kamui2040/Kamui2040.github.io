def directory_entry(name: str, detail: str, key: str|None=None, disabled: bool=False, support: bool=False) -> str:
    cls="directory-item"+(" directory-item--unavailable" if disabled else "")+(" directory-item--support" if support else "")
    start=f'<div class="{cls}">' if disabled else f'<a class="{cls}" href="{escape(DEST[key],quote=True)}" target="_blank" rel="noopener noreferrer"'+(' referrerpolicy="no-referrer"' if key=="crypto-donations" else "")+'>'
    end="</div>" if disabled else "</a>"
    return start+f'<strong>{name}</strong><span>{detail}</span>'+end

